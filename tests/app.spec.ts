import { test, expect } from '@playwright/test';
test('daily logging persists and goals validate', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('Let’s move, Alex')).toBeVisible();
  await page.getByRole('button', { name: 'Log daily steps' }).click();
  await page.getByRole('textbox', { name: 'Total steps today' }).fill('8123');
  await page.getByRole('button', { name: 'Save today’s steps' }).click();
  await expect(page.getByText('8,123', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Log a glass/ }).click();
  await page.getByRole('tab', { name: 'Profile', exact: true }).click();
  await page.getByRole('button', { name: 'Edit profile & goals' }).click();
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Sam');
  await page.getByRole('textbox', { name: 'Daily step goal' }).fill('0');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('alert')).toContainText('100 and 100,000');
  await page.getByRole('textbox', { name: 'Daily step goal' }).fill('9000');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.reload();
  await expect(page.getByText('Let’s move, Sam')).toBeVisible();
  await expect(page.getByText('8,123', { exact: true })).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('stride-v1')!));
  expect(saved.water).toBe(4); expect(saved.stepGoal).toBe(9000);
});
