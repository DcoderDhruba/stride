test('workout timer pauses, resumes, and saves to journal', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('tab', { name: 'Workouts', exact: true }).click();
  await page.getByRole('button', { name: 'Strength', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View Find your flow workout' })).toHaveCount(0);
  await page.getByRole('button', { name: 'View Stronger every day workout' }).click();
  await page.getByRole('button', { name: 'Start workout' }).click();
  await expect(page.getByText('00:02', { exact: true })).toBeVisible({ timeout: 5000 });
  await page.getByRole('button', { name: 'Pause session' }).click();
  const paused = await page.getByText(/^00:\d\d$/).textContent();
  await page.waitForTimeout(1200);
  await expect(page.getByText(paused!, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Resume session' }).click();
  await page.getByRole('button', { name: 'Finish & save workout' }).click();
  await expect(page.getByText('Your workout journal')).toBeVisible();
  await expect(page.getByText('Stronger every day', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Activity', exact: true }).click();
  await expect(page.getByText('Stronger every day', { exact: true })).toBeVisible();
});
test('mobile and desktop render without overflow or runtime errors', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page.getByText('Let’s move, Alex')).toBeVisible();
  await page.screenshot({ path: 'screenshots/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await expect(page.getByText('YOUR DAILY SPACE')).toBeVisible();
  await page.screenshot({ path: 'screenshots/desktop.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
